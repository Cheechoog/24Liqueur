foreach ($servicio in $servicios) {
    $dockerfilePath = "$base\$servicio\Dockerfile"

    $lineas = @(
        "FROM eclipse-temurin:17-jdk-alpine AS build",
        "WORKDIR /app",
        "COPY pom.xml ./parent-pom.xml",
        "COPY $servicio/pom.xml ./pom.xml",
        "COPY $servicio/src ./src",
        "RUN apk add --no-cache maven sed",
        "RUN sed -i '/<modules>/,/<\/modules>/d' ./parent-pom.xml",
        "RUN mvn install:install-file -Dfile=./parent-pom.xml -DgroupId=com.licor -DartifactId=licor-marketplace -Dversion=1.0.0-SNAPSHOT -Dpackaging=pom",
        "RUN mvn package -DskipTests",
        "FROM eclipse-temurin:17-jre-alpine",
        "WORKDIR /app",
        "COPY --from=build /app/target/*.jar app.jar",
        "ENTRYPOINT [""java"",""-jar"",""app.jar""]"
    )

    Set-Content -Path $dockerfilePath -Value $lineas -Encoding UTF8
    Write-Host "OK: $servicio"
}

